"""
clients/trading/proxy.py

HTTP client for a remote clob-proxy-server (clients/trading/server.py running
on a non-blocked host like valkyrie). Used by dev hosts that can't reach
Polymarket's CLOB POST endpoints directly because of geo-blocking.

Tunneling: typically `ssh -fN -L 8088:127.0.0.1:8088 valkyrie`, then point
PROXY_URL at http://127.0.0.1:8088.

Auth: shared bearer token in the Authorization header. Token is generated by
the operator and written into .env on both sides as PROXY_AUTH_TOKEN.
"""

from __future__ import annotations

from pathlib import Path
from typing import Optional

import requests

from common.env       import load_env
from common.orderbook import BookLevel, Order, OrderBook
from clients.trading.base import (
    BalanceInfo, CancelResult, OrderResult, TradingBackend,
)

ROOT     = Path(__file__).resolve().parent.parent.parent
ENV_FILE = ROOT / ".env"


class ProxyBackend(TradingBackend):
    """Client of clients/trading/server.py running remotely."""

    DEFAULT_TIMEOUT = 8.0

    def __init__(self, env: Optional[dict[str, str]] = None,
                 env_file: Path | str = ENV_FILE):
        env = env or load_env(env_file)

        url   = env.get("PROXY_URL", "http://127.0.0.1:8088").rstrip("/")
        token = env.get("PROXY_AUTH_TOKEN")
        if not token:
            raise RuntimeError(
                "PROXY_AUTH_TOKEN missing from .env — must match the server's token"
            )

        self.url   = url
        self._sess = requests.Session()
        self._sess.headers.update({"Authorization": f"Bearer {token}"})

        # Fail fast if the server is unreachable. Better here than mid-trading-loop.
        try:
            r = self._sess.get(f"{url}/health", timeout=self.DEFAULT_TIMEOUT)
            r.raise_for_status()
            if not r.json().get("ok"):
                raise RuntimeError(f"proxy /health not ok: {r.text[:200]}")
        except Exception as e:
            raise RuntimeError(f"clob-proxy unreachable at {url}: {e}") from e

    # ── TradingBackend ──────────────────────────────────────────────────────

    def get_book(self, token_id: str) -> OrderBook:
        r = self._sess.get(
            f"{self.url}/book", params={"token_id": token_id},
            timeout=self.DEFAULT_TIMEOUT,
        )
        r.raise_for_status()
        d = r.json()
        return OrderBook(
            bids=[BookLevel(float(x["price"]), float(x["size"])) for x in d.get("bids", [])],
            asks=[BookLevel(float(x["price"]), float(x["size"])) for x in d.get("asks", [])],
        )

    def place_order(self, order: Order) -> OrderResult:
        if order.side != "BUY":
            raise ValueError(f"Only BUY supported in this strategy, got {order.side!r}")
        if float(order.size) <= 0:
            return OrderResult(ok=False, raw={"error": "zero size"})

        try:
            r = self._sess.post(
                f"{self.url}/order",
                json={
                    "token_id": order.token_id,
                    "price":    float(order.limit_price),
                    "size":     float(order.size),
                    "side":     "BUY",
                    "note":     order.note,
                },
                timeout=self.DEFAULT_TIMEOUT,
            )
            r.raise_for_status()
            d = r.json()
        except Exception as e:
            return OrderResult(ok=False, raw={"error": str(e)})

        return OrderResult(
            ok       = bool(d.get("ok")),
            order_id = d.get("order_id"),
            status   = d.get("status"),
            raw      = d.get("raw"),
        )

    def cancel_order(self, order_id: str) -> CancelResult:
        try:
            r = self._sess.post(
                f"{self.url}/cancel", json={"order_id": order_id},
                timeout=self.DEFAULT_TIMEOUT,
            )
            r.raise_for_status()
            d = r.json()
        except Exception as e:
            return CancelResult(ok=False, raw={"error": str(e)})
        return CancelResult(ok=bool(d.get("ok")), raw=d.get("raw"))

    def get_balance(self) -> BalanceInfo:
        r = self._sess.get(f"{self.url}/balance", timeout=self.DEFAULT_TIMEOUT)
        r.raise_for_status()
        d = r.json()
        return BalanceInfo(
            usdc_balance       = float(d.get("balance_usdc", 0.0)),
            allowance_usdc     = float(d.get("allowance_usdc", 0.0)),
            spender_allowances = {},
            raw                = d.get("raw"),
        )
